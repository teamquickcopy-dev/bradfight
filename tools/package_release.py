#!/usr/bin/env python3
"""
package_release.py - player-ready zips of the game for Windows, macOS and Linux.

    python tools/package_release.py release.json [--platforms windows,linux] [--dist dist]

For each platform it takes the matching Ikemen GO release (downloaded once into .cache/), removes
Ikemen's sample characters and stages, adds the content built in engine/ (characters, stages,
screenpack, donation mod, CRT shader, save/config.ini), writes a select.def with only your roster,
renames the launchers to your game, adds README.txt + CREDITS.txt for players, checks that everything
the game will load is inside the package, and writes dist/<Name>-<version>-<platform>.zip + .sha256.

Build everything first (build_character.sh, build_stage.py, build_brand.py, install_crt.py ...):
this packs what is in engine/, it doesn't rebuild it.

Notes for players are in README.txt: the builds are unsigned, so Windows SmartScreen and macOS
Gatekeeper ask once; the Ikemen v1.0.0 macOS build is Apple Silicon only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import plistlib
import re
import shutil
import sys
import urllib.request
import zipfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
URL = "https://github.com/ikemen-engine/Ikemen-GO/releases/download/{v}/Ikemen_GO-{v}-{p}.zip"
EXEC_MODE = 0o755


def fetch(version: str, plat: str) -> Path:
    cache = ROOT / ".cache" / "ikemen"
    cache.mkdir(parents=True, exist_ok=True)
    z = cache / f"Ikemen_GO-{version}-{plat}.zip"
    if not z.exists():
        url = URL.format(v=version, p=plat)
        print(f"  downloading {url}")
        tmp = z.with_suffix(".part")
        with urllib.request.urlopen(url, timeout=300) as r, tmp.open("wb") as fh:
            shutil.copyfileobj(r, fh)
        tmp.replace(z)
    return z


def extract(zpath: Path, dest: Path) -> set[str]:
    """Extract, returning the relative paths that were executable in the zip."""
    execs = set()
    with zipfile.ZipFile(zpath) as z:
        for info in z.infolist():
            target = (dest / info.filename).resolve()
            if not str(target).startswith(str(dest.resolve())):
                raise SystemExit(f"unsafe path in {zpath.name}: {info.filename}")
            z.extract(info, dest)
            if (info.external_attr >> 16) & 0o111 and not info.is_dir():
                execs.add(info.filename)
    return execs


def find_ci(folder: Path, rel: str) -> Path | None:
    cur = folder
    for part in Path(rel.replace("\\", "/")).parts:
        if not cur.is_dir():
            return None
        hit = next((c for c in cur.iterdir() if c.name.lower() == part.lower()), None)
        if hit is None:
            return None
        cur = hit
    return cur


def ini_values(text: str, section: str) -> dict[str, str]:
    vals, cur = {}, None
    for line in text.splitlines():
        s = line.split(";", 1)[0].strip()
        if s.startswith("["):
            cur = s.strip("[]").strip().lower()
        elif cur == section.lower() and "=" in s:
            k, v = s.split("=", 1)
            vals.setdefault(k.strip().lower(), v.strip().strip('"'))
    return vals


def set_ini(text: str, section: str, key: str, value: str) -> str:
    sys.path.insert(0, str(ROOT / "tools"))
    from build_brand import set_in_section
    return set_in_section(text, section, key, value)


# --------------------------------------------------------------------------- content

def select_def(orig: str, chars: list[tuple[str, str]], stages: list[str], name: str) -> str:
    """Curated select.def: your roster and stages, original [Options] and later sections kept."""
    m = re.search(r"(?im)^[ \t]*\[options\][ \t]*(;.*)?$", orig)   # the real section, not a mention in a comment
    tail = orig[m.start():] if m else ""
    lines = [f"; {name} roster - generated by tools/package_release.py", "[Characters]"]
    lines += [f"{c}, stages/{s}.def" if s else c for c, s in chars]
    lines += ["", "[ExtraStages]"] + [f"stages/{s}.def" for s in stages] + ["", ""]
    return "\n".join(lines) + tail


def home_stages(engine_select: Path, chars: list[str], stages: list[str]) -> list[tuple[str, str]]:
    homes = {}
    if engine_select.exists():
        for line in engine_select.read_text(errors="replace").splitlines():
            parts = [p.strip() for p in line.split(";", 1)[0].split(",")]
            if parts and parts[0] in chars and len(parts) > 1 and parts[1].startswith("stages/"):
                homes[parts[0]] = Path(parts[1]).stem
    return [(c, homes.get(c, stages[0] if stages else "")) for c in chars]


def player_readme(cfg: dict, plat: str, donate: bool) -> str:
    name, ver = cfg["name"], cfg["version"]
    run = {"windows": f"Double-click {name}.exe.",
           "macos": f"Double-click {name}.command the first time (it clears the download quarantine and starts\n"
                    f"  the game), then open {name}.app. Needs a Mac with Apple Silicon (M1 or newer).",
           "linux": f"Run ./{name}.sh (or the {name}.desktop launcher)."}[plat]
    first = {"windows": "Windows may show \"Windows protected your PC\": click More info > Run anyway\n"
                        "  (the game isn't code-signed).",
             "macos": "If macOS says the app can't be opened, right-click it > Open > Open (the game isn't notarized).",
             "linux": "If it doesn't start, make sure the files are executable: chmod +x Ikemen_GO_Linux "
                      f"{name}.sh"}[plat]
    return f"""{name} {ver}
{'=' * (len(name) + len(ver) + 1)}

START
  {run}
  {first}

CONTROLS (keyboard, player 1; gamepads work too)
  Change them in Options > Input Settings > Key Config.
  Move ............ arrow keys
  Light punch / medium punch / heavy punch ... A / S / D
  Light kick / medium kick / heavy kick ...... Z / X / C
  Start / pause ... Enter
  Fullscreen ...... Alt+Enter

SETTINGS
  Your settings are saved in save/config.ini. Delete that file's [Video] ExternalShaders line
  (or set it empty) to turn off the CRT effect.
""" + ("""
SUPPORT
  Pick "KEEP THE RENT PAID" on the title screen.
""" if donate else "")


def credits(cfg: dict) -> str:
    return f"{cfg['name']} {cfg['version']}\n\n" + "\n".join(cfg.get("credits", [])) + "\n\nEngine license texts: LICENSES.txt\n"


def icns(icon_png: Path, out: Path) -> None:
    img = Image.open(icon_png).convert("RGBA").resize((512, 512), Image.Resampling.LANCZOS)
    img.save(out, format="ICNS", sizes=[(16, 16), (32, 32), (64, 64), (128, 128), (256, 256), (512, 512)])


# --------------------------------------------------------------------------- checks

def check_package(game: Path, cfg: dict, plat: str) -> list[str]:
    problems = []
    sel = (game / "data" / "select.def").read_text(errors="replace")
    for c in cfg["characters"]:
        d = find_ci(game / "chars" / c, f"{c}.def")
        if not d:
            problems.append(f"chars/{c}/{c}.def missing")
            continue
        for key, val in ini_values(d.read_text(errors="replace"), "files").items():
            if key == "stcommon" or not val:
                continue
            if not find_ci(d.parent, val):
                problems.append(f"{c}.def [Files] {key} = {val}: missing")
    for s in cfg["stages"]:
        st = game / "stages" / f"{s}.def"
        if not st.exists():
            problems.append(f"stages/{s}.def missing")
            continue
        spr = ini_values(st.read_text(errors="replace"), "bgdef").get("spr", "")
        if spr and not find_ci(st.parent, spr):
            problems.append(f"stages/{s}.def spr = {spr}: missing")
    for removed in ("kfm", "kfm720", "kfm_zss", "kfm_zaxis", "stage0", "stage1", "stageZ"):
        if re.search(rf"(?im)^\s*(stages/)?{removed}(\.def)?\s*(,|$)", sel):
            problems.append(f"select.def still lists removed sample content: {removed}")
    conf = (game / "save" / "config.ini").read_text(errors="replace")
    c = ini_values(conf, "config")
    motif = game / c.get("motif", "")
    if not motif.is_file():
        problems.append(f"config.ini Motif = {c.get('motif')}: missing")
    else:
        files = ini_values(motif.read_text(errors="replace"), "files")
        for key in ("spr", "logo.storyboard", "fight"):
            val = files.get(key, "")
            if val and not (find_ci(motif.parent, val) or find_ci(game / "data", val)):
                problems.append(f"screenpack [Files] {key} = {val}: missing")
    for icon in [p.strip() for p in c.get("windowicon", "").split(",") if p.strip()]:
        if not (game / icon).is_file():
            problems.append(f"WindowIcon {icon}: missing")
    for sh in [p.strip() for p in ini_values(conf, "video").get("externalshaders", "").split(",") if p.strip()]:
        for ext in (".vert", ".frag"):
            if not (game / (sh + ext)).is_file():
                problems.append(f"shader {sh}{ext}: missing")
    debug_stage = ini_values(conf, "debug").get("startstage", "")
    if debug_stage and not (game / debug_stage).is_file():
        problems.append(f"[Debug] StartStage = {debug_stage}: missing")
    mods = game / "external" / "mods" / "donate.lua"
    if mods.exists() and not (game / "external" / "mods" / "donate" / "qr.sff").exists():
        problems.append("donate.lua without donate/qr.sff")
    return problems


# --------------------------------------------------------------------------- main

def package(cfg: dict, plat: str, dist: Path) -> Path:
    name, ver, slug = cfg["name"], cfg["version"], cfg["slug"]
    eng = ROOT / "engine"
    stage_dir = dist / "staging" / f"{name}-{ver}-{plat}"
    if stage_dir.exists():
        shutil.rmtree(stage_dir)
    game = stage_dir / name
    game.mkdir(parents=True)
    execs = extract(fetch(cfg.get("ikemen_version", "v1.0.0"), plat), game)

    # Ikemen samples out, your content in
    for sub in ("chars", "stages"):
        for p in (game / sub).iterdir():
            shutil.rmtree(p) if p.is_dir() else p.unlink()
    (game / "README.md").unlink(missing_ok=True)
    for c in cfg["characters"]:
        src = eng / "chars" / c
        if not (src / f"{c}.def").exists():
            raise SystemExit(f"engine/chars/{c} isn't built (run build_character.sh {c})")
        shutil.copytree(src, game / "chars" / c)
    for s in cfg["stages"]:
        for ext in (".def", ".sff"):
            src = eng / "stages" / f"{s}{ext}"
            if not src.exists():
                raise SystemExit(f"engine/stages/{s}{ext} missing (run tools/build_stage.py)")
            shutil.copy2(src, game / "stages" / src.name)
    brand_dir = eng / "data" / slug
    if brand_dir.is_dir():
        shutil.copytree(brand_dir, game / "data" / slug)
    for rel in ("external/mods/donate.lua", "external/mods/donate"):
        src = eng / rel
        if src.is_dir():
            shutil.copytree(src, game / rel)
        elif src.exists():
            shutil.copy2(src, game / rel)
    for sh in (eng / "external" / "shaders").glob("CRT*"):
        shutil.copy2(sh, game / "external" / "shaders" / sh.name)
    (game / "save").mkdir(exist_ok=True)
    conf = (eng / "save" / "config.ini").read_text() if (eng / "save" / "config.ini").exists() else ""
    if cfg["stages"]:
        conf = set_ini(conf, "Debug", "StartStage", f"stages/{cfg['stages'][0]}.def")
    (game / "save" / "config.ini").write_text(conf)
    orig_sel = (game / "data" / "select.def").read_text(errors="replace")
    (game / "data" / "select.def").write_text(
        select_def(orig_sel, home_stages(eng / "data" / "select.def", cfg["characters"], cfg["stages"]),
                   cfg["stages"], name))
    (game / "README.txt").write_text(player_readme(cfg, plat, (game / "external" / "mods" / "donate.lua").exists()))
    (game / "CREDITS.txt").write_text(credits(cfg))
    icon = ROOT / "brand" / "icon.png"

    # launchers under your name
    if plat == "windows":
        (game / "Ikemen_GO.exe").rename(game / f"{name}.exe")
    elif plat == "macos":
        app_old, app = game / "I.K.E.M.E.N-Go.app", game / f"{name}.app"
        app_old.rename(app)
        plist_p = app / "Contents" / "Info.plist"
        plist = plistlib.loads(plist_p.read_bytes())
        plist.update(CFBundleName=name, CFBundleDisplayName=name, CFBundleIdentifier=f"com.{slug}.game",
                     CFBundleVersion=ver, CFBundleShortVersionString=ver)
        plist_p.write_bytes(plistlib.dumps(plist))
        if icon.exists():
            icns(icon, app / "Contents" / "Resources" / "icon.icns")
        cmd = (game / "Ikemen_GO.command").read_text().replace("I.K.E.M.E.N-Go.app", f"{name}.app")
        (game / "Ikemen_GO.command").unlink()
        (game / f"{name}.command").write_text(cmd)
        execs = {e.replace("I.K.E.M.E.N-Go.app", f"{name}.app") for e in execs if e != "Ikemen_GO.command"}
        execs |= {f"{name}.command", f"{name}.app/Contents/MacOS/bundle_run.sh",
                  f"{name}.app/Contents/MacOS/Ikemen_GO_MacOSARM"}
    else:
        (game / f"{name}.sh").write_text('#!/usr/bin/env bash\ncd "$(dirname "$0")"\nexec ./Ikemen_GO_Linux "$@"\n')
        execs |= {f"{name}.sh", "Ikemen_GO_Linux", "Ikemen_GO.command"}
        if icon.exists():
            shutil.copy2(icon, game / f"{slug}.png")
        (game / "Ikemen_GO.desktop").unlink(missing_ok=True)
        (game / f"{name}.desktop").write_text(
            f"[Desktop Entry]\nName={name}\nExec=./{name}.sh\nIcon={slug}.png\nTerminal=false\nType=Application\n"
            "Categories=Game;ArcadeGame;\n")
        execs.add(f"{name}.desktop")

    problems = check_package(game, cfg, plat)
    if problems:
        for p in problems:
            print(f"  ! {p}")
        raise SystemExit(f"{plat}: package check failed")

    # zip with unix permissions so launchers stay executable after unzip on macOS/Linux
    dist.mkdir(parents=True, exist_ok=True)
    out = dist / f"{name}-{ver}-{plat}.zip"
    tmp = out.with_suffix(".part")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted(stage_dir.rglob("*")):
            rel = p.relative_to(stage_dir).as_posix()
            info = zipfile.ZipInfo(rel + ("/" if p.is_dir() else ""), date_time=(2026, 1, 1, 0, 0, 0))
            inner = p.relative_to(game).as_posix() if p != game else ""
            mode = (0o755 if p.is_dir() or inner in execs else 0o644)
            info.external_attr = ((0o040000 if p.is_dir() else 0o100000) | mode) << 16
            info.create_system = 3
            if p.is_dir():
                z.writestr(info, b"")
            else:
                info.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(info, p.read_bytes())
    tmp.replace(out)
    digest = hashlib.sha256(out.read_bytes()).hexdigest()
    (dist / f"{out.name}.sha256").write_text(f"{digest}  {out.name}\n")
    shutil.rmtree(dist / "staging")
    print(f"  {out.name}: {out.stat().st_size / 1e6:.1f} MB, sha256 {digest[:16]}..., checks passed")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config", type=Path)
    ap.add_argument("--platforms", help="comma list (default: from the config)")
    ap.add_argument("--dist", type=Path, default=ROOT / "dist")
    args = ap.parse_args()
    cfg = json.loads(args.config.read_text())
    plats = args.platforms.split(",") if args.platforms else cfg["platforms"]
    outs = []
    for plat in plats:
        print(f"[{plat}]")
        outs.append(package(cfg, plat.strip(), args.dist.resolve()))
    itch = cfg.get("itch", {})
    user, game = itch.get("user") or "<itch-user>", itch.get("game") or cfg["slug"]
    print("\nupload to itch.io with butler (https://itch.io/docs/butler/):")
    for o in outs:
        chan = o.stem.rsplit("-", 1)[1]
        print(f"  butler push {o} {user}/{game}:{chan} --userversion {cfg['version']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
