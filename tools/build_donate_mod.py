#!/usr/bin/env python3
"""
build_donate_mod.py - generate the "KEEP THE RENT PAID" title-menu button as an Ikemen GO mod.

    python tools/build_donate_mod.py mods/donate.json [--engine engine]

Writes engine/external/mods/donate.lua (autoloaded by Ikemen; no engine files are edited) and
engine/external/mods/donate/qr.sff. Selecting the item opens the link in the player's browser and
shows a screen with the link and a QR code, which also covers machines where no browser can open
(Steam Deck game mode, fullscreen setups) and people watching on a stream.

Settings (mods/donate.json): url (https://, required), label (menu text), title, message, opened_text,
scan_text, close_text, before (menu item to insert above, e.g. "options" or "exit"), open_browser.

The URL may only contain plain URL characters (letters, digits and - . _ ~ : / ? # @ ! $ & * + , ; =).
No quotes, spaces, % or shell metacharacters are allowed, because it is passed to the system's
"open link" command.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
import textwrap
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_sff import Entry, build  # noqa: E402

SAFE_URL = re.compile(r"^https?://[A-Za-z0-9\-._~:/?#@!$&*+,;=]+$")   # keep in sync with donate.safeUrl
QR_PX = 320


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


LUA = r'''-- donate.lua - generated by tools/build_donate_mod.py from mods/donate.json. Edit the JSON and rebuild.
-- Adds a title-menu item that opens the support link in the browser and shows it on screen with a
-- QR code. Loaded automatically from external/mods/ (rename to -donate.lua to disable).

local CFG = {
	url = @URL@,
	label = @LABEL@,
	title = @TITLE@,
	message = @MESSAGE@,
	opened_text = @OPENED@,
	scan_text = @SCAN@,
	close_text = @CLOSE@,
	before = @BEFORE@,
	open_browser = @OPEN_BROWSER@,
	qr_sff = 'external/mods/donate/qr.sff',
	qr_size = @QR_PX@,
}

donate = {}

-- Only plain URL characters ever reach os.execute: no quotes, spaces, % or shell metacharacters.
function donate.safeUrl(url)
	return type(url) == 'string' and url:match('^https?://[%w%-%._~:/%?#@!%$&%*%+,;=]+$') ~= nil
end

function donate.platform()
	if package.config:sub(1, 1) == '\\' then
		return 'windows'
	end
	-- no process spawn needed: macOS always has this file
	local f = io.open('/System/Library/CoreServices/SystemVersion.plist', 'r')
	if f then
		f:close()
		return 'mac'
	end
	return 'linux'
end

-- Every command returns at once, so the game never waits on the browser.
function donate.openCommand(url, platform)
	if platform == 'windows' then
		-- No quotes: Go escapes inner quotes for cmd.exe in a way cmd can't read. & must be ^-escaped.
		return 'rundll32 url.dll,FileProtocolHandler ' .. url:gsub('&', '^&')
	elseif platform == 'mac' then
		return "open '" .. url .. "' >/dev/null 2>&1 &"
	end
	return "(xdg-open '" .. url .. "' || gio open '" .. url .. "') >/dev/null 2>&1 &"
end

function donate.open(url)
	if not CFG.open_browser or not donate.safeUrl(url) then
		return false
	end
	local ok, res = pcall(os.execute, donate.openCommand(url, donate.platform()))
	return ok and (res == 0 or res == true)
end

local qrAnim
local function getQrAnim()
	if qrAnim == nil then
		qrAnim = false
		local ok, sff = pcall(sffNew, CFG.qr_sff)
		if ok and sff then
			qrAnim = animNew(sff, '9000,0, 0,0, -1')
			animSetLocalcoord(qrAnim, motif.info.localcoord[1], motif.info.localcoord[2])
		end
	end
	return qrAnim or nil
end

-- Same structure as main.f_warning: menu background, dark overlay, text, plus the QR code.
function donate.screen(opened)
	local sec, background = motif[main.group], motif[main.background]
	local wi = motif.warning_info
	local overlay, titleData, textData = wi.overlay.RectData, wi.title.TextSpriteData, wi.text.TextSpriteData
	local w, h = motif.info.localcoord[1], motif.info.localcoord[2]
	local qr = getQrAnim()
	local qx, qy = w - CFG.qr_size - math.floor(w * 0.08), math.floor((h - CFG.qr_size) / 2)
	if qr then
		animSetPos(qr, qx, qy)
		animUpdate(qr)
	end
	textImgReset(titleData)
	textImgReset(textData)
	textImgSetText(titleData, CFG.title)
	textImgSetText(textData, CFG.message .. '\n\n' .. CFG.url .. '\n\n' ..
		(opened and CFG.opened_text or CFG.scan_text) .. '\n' .. CFG.close_text)
	textImgSetPos(textData, math.floor(w * 0.08), math.floor(h * 0.32))
	resetKey()
	esc(false)
	local frames = 0
	while true do
		frames = frames + 1
		-- ignore the first frames so the press that opened this screen doesn't also close it
		if frames > 20 then
			if esc() or getInput(-1, sec.menu.cancel.key) then
				esc(false)
				sndPlay(motif.Snd, wi.cancel.snd[1], wi.cancel.snd[2])
				break
			elseif getKey() ~= '' or getInput(-1, sec.menu.done.key) then
				sndPlay(motif.Snd, wi.done.snd[1], wi.done.snd[2])
				break
			end
		end
		clearColor(background.bgclearcolor[1], background.bgclearcolor[2], background.bgclearcolor[3])
		bgDraw(background.BGDef, 0)
		rectDraw(overlay)
		textImgDraw(titleData)
		textImgDraw(textData)
		if qr then
			animDraw(qr)
		end
		bgDraw(background.BGDef, 1)
		refresh()
	end
	resetKey()
	textImgReset(titleData)          -- give the shared warning box its own texts back
	textImgReset(textData)
	if resetTokenGuard then
		resetTokenGuard()
	end
end

main.t_itemname.donate = function(t, item)
	donate.screen(donate.open(CFG.url))
	return nil                       -- nil = stay on the title menu
end

if motif and motif.title_info and motif.title_info.menu then
	main.f_appendItemname(motif.title_info.menu, '', 'donate', CFG.label, CFG.before)
end
'''


def make_qr(url: str, out_png: Path) -> None:
    import qrcode
    from PIL import Image
    q = qrcode.QRCode(border=3, error_correction=qrcode.constants.ERROR_CORRECT_M)
    q.add_data(url)
    q.make(fit=True)
    img = q.make_image(fill_color="black", back_color="white").convert("RGBA")
    img.resize((QR_PX, QR_PX), Image.Resampling.NEAREST).save(out_png)


def wrap(text: str, width: int = 44) -> str:
    return "\n".join(textwrap.fill(p, width) for p in text.split("\n"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config", type=Path)
    ap.add_argument("--engine", type=Path, default=Path("engine"))
    args = ap.parse_args()
    cfg = json.loads(args.config.read_text())
    url = cfg.get("url", "").strip()
    if not url:
        print(f"error: set \"url\" in {args.config} (your Cash App / Ko-fi / PayPal.me / Patreon link)", file=sys.stderr)
        return 2
    if not SAFE_URL.match(url):
        print(f"error: url {url!r} must be https://... with plain URL characters only (no quotes, spaces or %)",
              file=sys.stderr)
        return 2
    mods = args.engine / "external" / "mods"
    if not mods.parent.is_dir():
        print(f"error: {args.engine} doesn't look like an Ikemen GO folder (no external/)", file=sys.stderr)
        return 2
    (mods / "donate").mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        png = Path(tmp) / "qr.png"
        make_qr(url, png)
        build([Entry(9000, 0, 0, 0, png)], (mods / "donate" / "qr.sff").resolve(), trim=False, dedupe=False, compress=9)

    lua = LUA
    for key, val in {
        "@URL@": lua_str(url), "@LABEL@": lua_str(cfg.get("label", "KEEP THE RENT PAID")),
        "@TITLE@": lua_str(cfg.get("title", "KEEP THE RENT PAID")),
        "@MESSAGE@": lua_str(wrap(cfg.get("message", ""))), "@OPENED@": lua_str(wrap(cfg.get("opened_text", ""))),
        "@SCAN@": lua_str(wrap(cfg.get("scan_text", ""))), "@CLOSE@": lua_str(cfg.get("close_text", "")),
        "@BEFORE@": lua_str(cfg.get("before", "options")),
        "@OPEN_BROWSER@": "true" if cfg.get("open_browser", True) else "false", "@QR_PX@": str(QR_PX),
    }.items():
        lua = lua.replace(key, val)
    (mods / "donate.lua").write_text(lua, encoding="utf-8")
    print(f"wrote {mods / 'donate.lua'} and {mods / 'donate' / 'qr.sff'}: menu item {cfg.get('label')!r} "
          f"above {cfg.get('before', 'options')!r} -> {url}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
