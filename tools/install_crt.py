#!/usr/bin/env python3
"""
install_crt.py - CRT / bloom post-processing for Ikemen GO.

    python tools/install_crt.py crt          # curved CRT glass + scanlines + aperture grille + bloom
    python tools/install_crt.py flat         # same look, no curvature (lifebar corners stay sharp)
    python tools/install_crt.py off          # back to the plain picture
    options: --engine engine  --scanlines 0.30  --bloom 0.25  --curvature 0.035  --mask 0.10

Writes engine/external/shaders/CRT.vert/.frag and CRT_Flat.vert/.frag, and sets
[Video] ExternalShaders in engine/save/config.ini (created if the game hasn't made one yet; Ikemen
fills every other setting from its defaults). This is for the default OpenGL renderer. The
experimental Vulkan renderer needs .spv builds of the same files:
    glslangValidator -V --glsl-version 450 CRT.frag -o CRT.frag.spv   (and the same for .vert)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

VERT = """// {name}.vert - generated by tools/install_crt.py
#if __VERSION__ >= 450
	layout(push_constant, std430) uniform u {{
		vec2 TextureSize;
		float CurrentTime;
	}};
	layout(location = 0) in vec2 VertCoord;
	layout(location = 0) out vec2 vTexCoord;
#else
	in vec2 VertCoord;
	out vec2 vTexCoord;
#endif

void main() {{
	gl_Position = vec4(VertCoord, 0.0, 1.0);
	vTexCoord = (VertCoord + 1.0) / 2.0;
}}
"""

FRAG = """// {name}.frag - generated by tools/install_crt.py. Re-run the tool to change these values.
#define CURVATURE {curvature}          // barrel distortion, 0 = flat glass
#define SCANLINE_STRENGTH {scanlines}  // 0-1, darkness between scanlines
#define SCANLINE_PX 3.0                // output pixels per scanline: crisp at any window size
#define MASK_STRENGTH {mask}           // RGB aperture-grille tint
#define BLOOM_STRENGTH {bloom}         // glow around bright areas (neon, hit sparks)
#define VIGNETTE {vignette}            // corner darkening

#if __VERSION__ >= 450
	layout(push_constant, std430) uniform u {{
		vec2 TextureSize;
		float CurrentTime;
	}};
	layout(binding = 0) uniform sampler2D Texture;
	layout(location = 0) in vec2 vTexCoord;
	layout(location = 0) out vec4 FragColor;
#else
	uniform vec2 TextureSize;
	uniform sampler2D Texture;
	in vec2 vTexCoord;
	out vec4 FragColor;
#endif

vec2 curve(vec2 uv) {{
	uv = uv * 2.0 - 1.0;
	uv *= 1.0 + CURVATURE * dot(uv, uv);
	return uv * 0.5 + 0.5;
}}

vec3 bright(vec2 uv) {{
	vec3 c = texture(Texture, uv).rgb;
	return max(c - 0.75, 0.0) * 4.0;      // only near-white parts glow: neon, sparks, lights
}}

void main(void) {{
	vec2 outSize = TextureSize.x > 0.0 ? TextureSize : vec2(textureSize(Texture, 0));
	vec2 texel = 1.0 / vec2(textureSize(Texture, 0));
	vec2 uv = curve(vTexCoord);

	// outside the curved glass: black, with a soft 1.5px edge
	vec2 edge = smoothstep(vec2(0.0), 1.5 / outSize, uv) * smoothstep(vec2(0.0), 1.5 / outSize, 1.0 - uv);
	float inside = edge.x * edge.y;

	vec3 col = texture(Texture, uv).rgb;

	// bloom: 8-tap ring at two radii
	vec3 glow = vec3(0.0);
	for (int i = 0; i < 8; i++) {{
		float a = float(i) * 0.785398;
		vec2 d = vec2(cos(a), sin(a)) * texel;
		glow += bright(uv + d * 2.0) + bright(uv + d * 5.0);
	}}
	col += glow / 16.0 * BLOOM_STRENGTH;

	// scanlines follow the curved glass, smooth profile so they never alias
	float line = 0.5 + 0.5 * cos(6.2831853 * uv.y * outSize.y / SCANLINE_PX);
	col *= 1.0 - SCANLINE_STRENGTH * line;
	col *= 1.0 / (1.0 - SCANLINE_STRENGTH * 0.5);   // scanlines average to (1 - S/2): undo exactly

	// aperture grille: R, G, B columns in output pixels
	float c = mod(floor(gl_FragCoord.x), 3.0);
	// each column boosts one channel and dims the other two: average stays 1.0
	vec3 mask = vec3(1.0 - MASK_STRENGTH * 0.5);
	mask += vec3(step(c, 0.5), step(0.5, c) * step(c, 1.5), step(1.5, c)) * MASK_STRENGTH * 1.5;
	col *= mask;

	// vignette
	vec2 v = vTexCoord * (1.0 - vTexCoord.yx);
	col *= mix(1.0, pow(clamp(v.x * v.y * 16.0, 0.0, 1.0), 0.25), VIGNETTE);

	FragColor = vec4(col * inside, 1.0);
}}
"""


def set_config(cfg: Path, value: str) -> None:
    """Set [Video] ExternalShaders, keeping every other line of an existing config untouched."""
    lines = cfg.read_text(encoding="utf-8").splitlines(keepends=True) if cfg.exists() else []
    out, in_video, done, has_video = [], False, False, False
    for line in lines:
        s = line.strip()
        if s.startswith("["):
            if in_video and not done:
                out.append(f"ExternalShaders   = {value}\n")
                done = True
            in_video = s.lower() == "[video]"
            has_video = has_video or in_video
        elif in_video and re.match(r"(?i)^externalshaders\s*=", s):
            line = f"ExternalShaders   = {value}\n"
            done = True
        out.append(line)
    if in_video and not done:
        out.append(f"ExternalShaders   = {value}\n")
    elif not has_video:
        out += (["\n"] if out else []) + ["[Video]\n", f"ExternalShaders   = {value}\n"]
    cfg.parent.mkdir(parents=True, exist_ok=True)
    cfg.write_text("".join(out), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("variant", choices=("crt", "flat", "off"))
    ap.add_argument("--engine", type=Path, default=Path("engine"))
    ap.add_argument("--scanlines", type=float, default=0.30)
    ap.add_argument("--bloom", type=float, default=0.25)
    ap.add_argument("--curvature", type=float, default=0.035)
    ap.add_argument("--mask", type=float, default=0.10)
    args = ap.parse_args()
    shaders = args.engine / "external" / "shaders"
    if not shaders.is_dir():
        print(f"error: {shaders} not found; is --engine an Ikemen GO folder?", file=sys.stderr)
        return 2
    for name, curvature, vignette in (("CRT", args.curvature, 0.25), ("CRT_Flat", 0.0, 0.10)):
        vals = dict(name=name, curvature=f"{curvature:.4f}", scanlines=f"{args.scanlines:.3f}",
                    mask=f"{args.mask:.3f}", bloom=f"{args.bloom:.3f}", vignette=f"{vignette:.3f}")
        (shaders / f"{name}.vert").write_text(VERT.format(**vals))
        (shaders / f"{name}.frag").write_text(FRAG.format(**vals))
    value = {"crt": "external/shaders/CRT", "flat": "external/shaders/CRT_Flat", "off": ""}[args.variant]
    set_config(args.engine / "save" / "config.ini", value)
    print(f"shaders written to {shaders}; {args.engine / 'save' / 'config.ini'}: ExternalShaders = {value or '(none)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
